const LANGUAGES = {
  fr: { name: 'Français', dict: FR },
  en: { name: 'English', dict: EN },
};

const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem('lang') || 'fr');

  const setLanguage = (l) => {
    localStorage.setItem('lang', l);
    setLang(l);
  };

  const t = (key, vars) => {
    let str = LANGUAGES[lang]?.dict[key] ?? FR[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        str = str.replaceAll(`{${k}}`, v);
      }
    }
    return str;
  };

  const formatDate = (value) => {
    if (!value) return '—';
    const locale = lang === 'fr' ? 'fr-FR' : 'en-GB';
    return new Date(value).toLocaleString(locale, { dateStyle: 'short', timeStyle: 'short' });
  };

  return (
    <LanguageContext.Provider value={{ lang, setLanguage, t, formatDate }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLang() {
  const ctx = useContext(LanguageContext);
  if (!ctx) {
    throw new Error('useLang doit être utilisé dans <LanguageProvider>');
  }
  return ctx;
}

export { LANGUAGES };